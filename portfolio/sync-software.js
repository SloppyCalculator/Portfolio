#!/usr/bin/env node
/**
 * sync-software.js
 * Scans software/{project}/README.md and regenerates software/data.js
 *
 * Run: node sync-software.js
 *
 * === .md FORMAT (in each project's README.md) ===
 *
 * # Project Title
 * **Tech Stack**: Technology 1, Technology 2
 * **Context**: Optional short context line (shows under CRT header)
 *
 * ## System Highlights  (or ## Features, ## Description, etc.)
 * - Bullet 1
 * - Bullet 2
 * ...
 *
 * === ADDING A NEW PROJECT ===
 * 1. Create a new folder: software/my-project/
 * 2. Add software/my-project/README.md using the format above
 * 3. Run: node sync-software.js
 */

const fs   = require('fs');
const path = require('path');

const SOFTWARE_DIR = path.join(__dirname, 'software');
const OUT_FILE     = path.join(__dirname, 'software', 'data.js');

function discoverProjectFolders() {
    return fs.readdirSync(SOFTWARE_DIR, { withFileTypes: true })
        .filter(d => d.isDirectory())
        .map(d => d.name)
        .filter(name => fs.existsSync(path.join(SOFTWARE_DIR, name, 'README.md')))
        .sort();
}

function extractField(lines, label) {
    const prefix = `**${label}**:`.toLowerCase();
    for (const l of lines) {
        if (l.toLowerCase().startsWith(prefix)) {
            return l.slice(prefix.length).replace(/\s+/g, ' ').trim();
        }
    }
    return '';
}

function parseProjectReadme(folderName) {
    const filePath = path.join(SOFTWARE_DIR, folderName, 'README.md');
    const raw   = fs.readFileSync(filePath, 'utf8');
    const lines = raw.split('\n');

    // Title
    const titleLine = lines.find(l => l.startsWith('# '));
    const title = titleLine ? titleLine.replace(/^#\s+/, '').trim() : folderName;

    const tech    = extractField(lines, 'Tech Stack') || extractField(lines, 'Tech');
    const context = extractField(lines, 'Context')    || '';

    // Description body — take content under any ## section
    // Strip ** markdown and collect bullet points for CRT display
    const bodyLines = [];
    let inSection = false;
    for (const l of lines) {
        if (/^##\s+/.test(l) && !/^###/.test(l)) { inSection = true; continue; }
        if (l.startsWith('# ') || l.startsWith('**')) { inSection = false; continue; }
        if (inSection) bodyLines.push(l);
    }
    const description = bodyLines
        .map(l => l.replace(/\*\*([^*]+)\*\*/g, '$1').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1'))
        .filter(l => l.trim())
        .join('\n');

    // CRT-formatted content string
    const crtTitle = title.toUpperCase();
    const techDisplay = tech || 'N/A';
    const descDisplay = description || 'No description available.';
    const contextLine = context ? `> ${context.toUpperCase()}\n` : '';

    const content = `> BOOTING SYSTEM...\n> LOADING ${crtTitle}...\n${contextLine}\n[ TECH STACK ]\n${techDisplay}\n\n[ DESCRIPTION ]\n${descDisplay}`;

    return {
        folderName,
        title: crtTitle,
        tech: techDisplay,
        content,
        folder: `${folderName}/`,
        file: `software/${folderName}/README.md`
    };
}

function generateDataJs(projects) {
    const entries = projects.map((p, i) => {
        const key = String(i + 1);
        // Use JSON.stringify for safe string embedding
        const title   = JSON.stringify(p.title);
        const tech    = JSON.stringify(p.tech);
        const content = JSON.stringify(p.content);
        const folder  = JSON.stringify(p.folder);
        const file    = JSON.stringify(p.file);
        return `    ${JSON.stringify(key)}: {\n        title: ${title},\n        tech: ${tech},\n        content: ${content},\n        folder: ${folder},\n        file: ${file}\n    }`;
    });

    return `/**
 * Software Projects Data Module
 * Powers the retro cassette tape rack and CRT monitor terminal in the portfolio.
 *
 * AUTO-GENERATED by sync-software.js — do not edit by hand.
 * To add or edit a project:
 *   1. Create/edit software/<project-folder>/README.md
 *   2. Run: node sync-software.js
 */
window.softwareData = {
${entries.join(',\n')}
};
`;
}

// Main
const folders  = discoverProjectFolders();
if (folders.length === 0) {
    console.error('No project folders with README.md found under software/');
    process.exit(1);
}

const projects = folders.map(f => parseProjectReadme(f));
const output   = generateDataJs(projects);

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`✅ software/data.js updated — ${projects.length} project(s) synced:`);
projects.forEach(p => console.log(`   • ${p.title}`));
