#!/usr/bin/env node
/**
 * sync-research.js
 * Scans research/papers/*.md and regenerates research/data.js
 *
 * Run: node sync-research.js
 *
 * === .md FORMAT ===
 * # Paper Title
 * **Authors**: Name, et al.
 * **Venue**: Conference / Journal, Year
 * **Primary Discipline**: Topic Area
 *
 * ## Abstract
 * First paragraph is used as the snippet.
 * Full body is stored in `details`.
 */

const fs   = require('fs');
const path = require('path');

const PAPERS_DIR = path.join(__dirname, 'research', 'papers');
const OUT_FILE   = path.join(__dirname, 'research', 'data.js');

function slugify(str) {
    return str.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

function extractField(lines, label) {
    const prefix = `**${label}**:`.toLowerCase();
    for (const l of lines) {
        if (l.toLowerCase().startsWith(prefix)) {
            return l.slice(prefix.length).replace(/\s+/g, ' ').trim();
        }
    }
    return '';
}

function parsePaperMd(filePath) {
    const raw  = fs.readFileSync(filePath, 'utf8');
    const lines = raw.split('\n');
    const filename = path.basename(filePath, '.md');

    // Title = first # heading
    const titleLine = lines.find(l => l.startsWith('# '));
    const title = titleLine ? titleLine.replace(/^#\s+/, '').trim() : filename;

    const authors    = extractField(lines, 'Authors');
    const venue      = extractField(lines, 'Venue');
    const discipline = extractField(lines, 'Primary Discipline') || extractField(lines, 'Discipline');

    // Snippet = first non-empty paragraph after ## Abstract
    let abstractIdx = lines.findIndex(l => /^##\s+Abstract/i.test(l));
    let snippet = '';
    if (abstractIdx !== -1) {
        for (let i = abstractIdx + 1; i < lines.length; i++) {
            const t = lines[i].trim();
            if (t && !t.startsWith('#')) {
                snippet = t.replace(/\*\*/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
                if (snippet.length > 220) snippet = snippet.slice(0, 217) + '...';
                break;
            }
        }
    }

    // Details = simple HTML from abstract section
    // We store a brief rich text; full content is fetched at runtime from `file`
    const bodyAfterTitle = lines.slice(1).filter(l => !l.startsWith('**')).join('\n').trim();
    const abstractBody = abstractIdx !== -1
        ? lines.slice(abstractIdx + 1).join('\n').trim()
        : bodyAfterTitle;

    // Convert basic markdown to HTML for the inline details fallback
    const detailsHtml = '<strong>Abstract &amp; Methodology:</strong> ' +
        (abstractBody.split('\n\n')[0] || snippet).replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');

    const id = slugify(filename);

    return {
        id,
        title,
        authors: authors || 'J Sofalas',
        snippet: snippet || title,
        details: detailsHtml,
        file: `research/papers/${filename}.md`
    };
}

function generateDataJs(papers) {
    const entries = papers.map(p => {
        const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
        return [
            '    {',
            `        id: "${esc(p.id)}",`,
            `        title: "${esc(p.title)}",`,
            `        authors: "${esc(p.authors)}",`,
            `        snippet: "${esc(p.snippet)}",`,
            `        details: "${esc(p.details)}",`,
            `        file: "${esc(p.file)}"`,
            '    }'
        ].join('\n');
    });

    return `/**
 * Research Data Module
 * Powers the interactive Google Scholar browser in the portfolio.
 *
 * AUTO-GENERATED by sync-research.js — do not edit by hand.
 * Edit the .md files in research/papers/ and re-run: node sync-research.js
 */
window.researchData = [
${entries.join(',\n')}
];
`;
}

// Main
const files = fs.readdirSync(PAPERS_DIR)
    .filter(f => f.endsWith('.md'))
    .sort();

if (files.length === 0) {
    console.error('No .md files found in research/papers/');
    process.exit(1);
}

const papers = files.map(f => parsePaperMd(path.join(PAPERS_DIR, f)));
const output = generateDataJs(papers);

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`✅ research/data.js updated — ${papers.length} paper(s) synced:`);
papers.forEach(p => console.log(`   • ${p.title}`));
